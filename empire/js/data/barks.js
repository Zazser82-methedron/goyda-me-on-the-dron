export function bark(kind) {
  const a = BARKS[kind] || ['ГОЙДА!'];
  // без Math.random в воркфлоу-скриптах нельзя — но это игровой браузерный JS, тут можно
  return a[Math.floor(Math.random() * a.length)];
}
